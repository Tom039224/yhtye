#!/usr/bin/env bash
# Prepare everything the Windows 11 test VM needs in $VM_DIR (default ~/VMs/win11), except the ISO
# (download-iso.sh). Idempotent: existing disk, keys, passwords and firmware variables are kept.
set -euo pipefail
source "$(dirname "${BASH_SOURCE[0]}")/common.sh"

command -v qemu-system-x86_64 >/dev/null || die "qemu-system-x86_64 is not installed"
with_tools_env swtpm --version >/dev/null 2>&1 \
  || die "swtpm does not run (see scripts/windows-vm/README.md: 'swtpm / qemu-img が動かないとき')"
QEMU_IMG="$(find_tool qemu-img)" || die "qemu-img is not installed"
[[ -r "$OVMF_CODE" && -r "$OVMF_VARS_TEMPLATE" ]] || die "OVMF firmware not found ($OVMF_CODE)"
[[ -w /dev/kvm ]] || die "/dev/kvm is not writable"

mkdir -p "$VM_DIR" "$TPM_DIR"
chmod 700 "$VM_DIR"

# Dedicated SSH key; existing keys in ~/.ssh are never touched.
if [[ ! -f "$SSH_KEY" ]]; then
  mkdir -p "$HOME/.ssh" && chmod 700 "$HOME/.ssh"
  ssh-keygen -q -t ed25519 -N "" -C "yhtye-win11-vm" -f "$SSH_KEY"
fi

random_password() {
  # Letters and digits only: no XML escaping, no shell quoting surprises.
  python3 -c 'import secrets, string; a = string.ascii_letters + string.digits; print("Yh" + "".join(secrets.choice(a) for _ in range(18)))'
}

if [[ ! -f "$CONFIG" ]]; then
  umask 077
  cat >"$CONFIG" <<EOF
# Generated by scripts/windows-vm/prepare.sh. Contains passwords; keep it out of git.
ADMIN_USER=yhtye
ADMIN_PASSWORD=$(random_password)
JA_USER=日本語ユーザー
JA_PASSWORD=$(random_password)
COMPUTER_NAME=YHTYE-WIN11
UI_LANGUAGE=${WIN11_VM_LANGUAGE:-ja-JP}
LOCALE=${WIN11_VM_LANGUAGE:-ja-JP}
INPUT_LOCALE=${WIN11_VM_INPUT_LOCALE:-0411:00000411}
TIMEZONE="${WIN11_VM_TIMEZONE:-Tokyo Standard Time}"
IMAGE_INDEX=1
EOF
  umask 022
fi
# Exported so the template renderer below can read them.
set -a
load_config
set +a

# Unattend media: autounattend.xml at the root, setup scripts and the public key under yhtye-vm\.
stage="$VM_DIR/unattend"
rm -rf "$stage"
mkdir -p "$stage/yhtye-vm"
python3 - "$SCRIPT_DIR/autounattend.xml.in" "$stage/autounattend.xml" <<'EOF'
import os, re, sys
text = open(sys.argv[1], encoding="utf-8").read()
def sub(m):
    value = os.environ.get(m.group(1))
    if value is None:
        sys.exit(f"autounattend.xml.in: no value for @{m.group(1)}@")
    return value
open(sys.argv[2], "w", encoding="utf-8").write(re.sub(r"@([A-Z_]+)@", sub, text))
EOF
cp "$SCRIPT_DIR/firstlogon.ps1" "$SCRIPT_DIR/install-tools.ps1" "$SCRIPT_DIR/run-gui.ps1" \
  "$SCRIPT_DIR/set-autologon.ps1" "$stage/yhtye-vm/"
cp "$SSH_KEY.pub" "$stage/yhtye-vm/authorized_keys"
# Name and password of the Japanese-named administrator that firstlogon.ps1 creates (UTF-8).
printf '%s\n%s\n' "$JA_USER" "$JA_PASSWORD" >"$stage/yhtye-vm/ja-user.txt"
chmod -R go-rwx "$stage"

if python3 -c 'import pycdlib' 2>/dev/null; then
  python3 "$SCRIPT_DIR/make-iso.py" "$stage" "$UNATTEND_ISO" UNATTEND
elif command -v uv >/dev/null; then
  uv run --quiet --no-project --with pycdlib python3 "$SCRIPT_DIR/make-iso.py" "$stage" "$UNATTEND_ISO" UNATTEND
else
  die "pycdlib is needed to build unattend.iso (pip install --user pycdlib, or install uv)"
fi
chmod 600 "$UNATTEND_ISO"

[[ -f "$DISK" ]] || with_tools_env "$QEMU_IMG" create -q -f qcow2 "$DISK" "$VM_DISK_SIZE"
[[ -f "$OVMF_VARS" ]] || cp "$OVMF_VARS_TEMPLATE" "$OVMF_VARS"

umask 077
cat >"$VM_DIR/README.md" <<EOF
# Windows 11 検証用 VM (Yhtye)

scripts/windows-vm/prepare.sh が生成。パスワードを含むので、リポジトリに入れない。

- 管理者 (SSH 用・自動ログオン): \`$ADMIN_USER\` / \`$ADMIN_PASSWORD\`
- 管理者 (日本語ユーザー名の検証用): \`$JA_USER\` / \`$JA_PASSWORD\`
- コンピューター名: $COMPUTER_NAME、言語: $UI_LANGUAGE
- SSH: \`ssh -i $SSH_KEY -p $SSH_PORT $ADMIN_USER@127.0.0.1\` (公開鍵認証のみ。既定のシェルは PowerShell)
- VNC: 127.0.0.1:$((5900 + VNC_DISPLAY)) (パスワード無し。ホストの外からは届かない)
- 操作: scripts/windows-vm/vm.sh (start / stop / status / ssh / screenshot / vnc)。詳細は scripts/windows-vm/README.md

| ファイル | 中身 |
| --- | --- |
| win11-enterprise-eval.iso | Windows 11 Enterprise 評価版 (90 日) |
| disk.qcow2 | システムディスク ($VM_DISK_SIZE、シン) |
| OVMF_VARS.4m.fd | UEFI 変数 |
| tpm/ | swtpm の TPM 2.0 の状態 |
| unattend.iso, unattend/ | 無人インストールのメディアとその中身 |
| vm.env | ユーザー名・パスワードなどの設定 |
| tools/ | ホストの swtpm / qemu-img を動かすための追加ライブラリ (あれば) |
EOF
umask 022

echo "prepared $VM_DIR"
echo "next: $SCRIPT_DIR/vm.sh install   (needs $ISO; see download-iso.sh)"
